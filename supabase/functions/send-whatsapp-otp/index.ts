/**
 * Baduma.sl — Send WhatsApp OTP
 *
 * Sends a one-time password via Twilio WhatsApp for customer/driver sign-in.
 *
 * Supports two modes:
 *
 * 1. "native" (default) — verifyOtp()-compatible
 *    Triggers OTP generation inside Supabase Auth via the service-role key
 *    (POST /auth/v1/otp). Supabase stores the OTP internally and delivers it
 *    through the configured Phone provider (Twilio WhatsApp). The client then
 *    verifies with `supabase.auth.verifyOtp({ phone, token, type: 'sms' })`.
 *
 *    The Edge Function additionally sends a branded WhatsApp notification via
 *    Twilio so the user gets a consistent Baduma.sl branded message.
 *
 * 2. "custom" — full control over the WhatsApp template
 *    The Edge Function generates its own OTP, persists it in the `otp_codes`
 *    table, and sends it via Twilio using an approved WhatsApp template.
 *    Verification is done by the `verify-whatsapp-otp` Edge Function (not
 *    `supabase.auth.verifyOtp`), because the OTP was not generated by Supabase
 *    Auth.
 *
 * Required env vars (set in the Supabase Dashboard → Edge Functions → Variables):
 *   SUPABASE_URL                 — e.g. https://xyzcompany.supabase.co
 *   SUPABASE_SERVICE_ROLE_KEY    — service role key (secret)
 *   TWILIO_ACCOUNT_SID           — Twilio account SID
 *   TWILIO_AUTH_TOKEN            — Twilio auth token (secret)
 *   TWILIO_WHATSAPP_SENDER       — e.g. "whatsapp:+14155238886"
 */

import { createClient } from '@supabase/supabase-js';
import Twilio from 'twilio';

const SUPABASE_URL = process.env.SUPABASE_URL;
const SUPABASE_SERVICE_ROLE_KEY = process.env.SUPABASE_SERVICE_ROLE_KEY;
const TWILIO_ACCOUNT_SID = process.env.TWILIO_ACCOUNT_SID;
const TWILIO_AUTH_TOKEN = process.env.TWILIO_AUTH_TOKEN;
const TWILIO_WHATSAPP_SENDER = process.env.TWILIO_WHATSAPP_SENDER;

function normalizePhone(phone: unknown): string {
  return String(phone || '').replace(/[\s-]/g, '');
}

/** Generate a cryptographically random 6-digit OTP. */
function generateOtp(): string {
  const bytes = new Uint32Array(1);
  crypto.getRandomValues(bytes);
  return String(bytes[0] % 1000000).padStart(6, '0');
}

function isValidPhone(phone: string): boolean {
  return /^\+?[0-9]{7,15}$/.test(phone);
}

export default async function handler(req: Request): Promise<Response> {
  if (req.method !== 'POST') {
    return new Response('Method not allowed', { status: 405 });
  }

  const body = await req.json().catch(() => ({}));
  const phone = normalizePhone(body.phone);
  const mode = body.mode === 'custom' ? 'custom' : 'native';

  if (!isValidPhone(phone)) {
    return new Response(JSON.stringify({ error: 'Invalid phone number' }), { status: 400 });
  }

  const supabase = createClient(SUPABASE_URL!, SUPABASE_SERVICE_ROLE_KEY!);
  const twilio = Twilio(TWILIO_ACCOUNT_SID!, TWILIO_AUTH_TOKEN!);

  // ---------------------------------------------------------------------------
  // Mode 1 — "native": trigger OTP generation in Supabase Auth (verifyOtp-compatible)
  // ---------------------------------------------------------------------------
  if (mode === 'native') {
    const { error: otpError } = await supabase.auth.signInWithOtp({ phone });
    if (otpError) {
      return new Response(JSON.stringify({ error: otpError.message }), { status: 400 });
    }

    // Branded supplementary notification via Twilio WhatsApp.
    await twilio.messages.create({
      from: TWILIO_WHATSAPP_SENDER!,
      to: `whatsapp:+${phone}`,
      body: '🍚 Your Baduma.sl verification code has been sent. Enter it to complete sign-in.',
    });

    return new Response(
      JSON.stringify({ success: true, mode, message: 'OTP sent via WhatsApp' }),
      { status: 200 }
    );
  }

  // ---------------------------------------------------------------------------
  // Mode 2 — "custom": Edge Function owns the OTP, sends via approved template
  // ---------------------------------------------------------------------------
  const otp = generateOtp();
  const expiresAt = new Date(Date.now() + 10 * 60 * 1000).toISOString(); // 10 minutes

  // Persist the OTP in Postgres.
  const { error: dbError } = await supabase.from('otp_codes').insert({
    phone,
    code: otp,
    expires_at: expiresAt,
    used: false,
  });
  if (dbError) {
    return new Response(JSON.stringify({ error: 'Failed to store OTP' }), { status: 500 });
  }

  // Send via Twilio WhatsApp with a custom approved template.
  await twilio.messages.create({
    from: TWILIO_WHATSAPP_SENDER!,
    to: `whatsapp:+${phone}`,
    body: `Your Baduma.sl verification code is ${otp}`,
  });

  return new Response(
    JSON.stringify({ success: true, mode, message: 'OTP sent via WhatsApp' }),
    { status: 200 }
  );
}
